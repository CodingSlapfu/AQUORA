#!/usr/bin/env python3
"""Generate tuned lexical PCM using Flite's CMU US SLT statistical vocoder."""
import ctypes as c
import sys
import tempfile
import wave
from pathlib import Path

import numpy as np
from scipy.signal import resample_poly

WORDS = ("shine", "free", "fly", "stay", "away", "home", "hope", "alive", "tonight", "forever")
RATE, PERIOD = 11025, 33
F0 = RATE / PERIOD

def bind(lib, name, args, result):
    function = getattr(lib, name)
    function.argtypes, function.restype = args, result
    return function

def render_words():
    lib = c.CDLL("libflite.so.1", mode=c.RTLD_GLOBAL)
    voice_library = c.CDLL("libflite_cmu_us_slt.so.1")
    pointer, string = c.c_void_p, c.c_char_p
    bind(lib, "flite_init", [], c.c_int)()
    voice = bind(voice_library, "register_cmu_us_slt", [string], pointer)(None)
    features = (pointer * 2).from_address(voice)[1]
    setting = bind(lib, "flite_feat_set_float", [pointer, string, c.c_float], None)
    setting(features, b"int_f0_target_mean", F0)
    setting(features, b"int_f0_target_stddev", 0.0)
    setting(features, b"duration_stretch", 0.82)
    render = bind(lib, "flite_text_to_wave", [string, pointer], pointer)
    save = bind(lib, "cst_wave_save_riff", [pointer, string], c.c_int)
    discard = bind(lib, "delete_wave", [pointer], None)
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "render.wav"
        for word in WORDS:
            output = render(word.encode(), voice)
            assert output and save(output, bytes(path)) == 0
            discard(output)
            with wave.open(str(path)) as wav:
                raw = np.frombuffer(wav.readframes(wav.getnframes()), dtype="<i2").astype(float)
                assert wav.getframerate() == 16000 and wav.getnchannels() == 1
            samples = resample_poly(raw, 441, 640)
            audible = np.flatnonzero(np.abs(samples) > max(abs(samples)) * .014)
            samples = samples[max(0, audible[0]-44):audible[-1]+67]
            # Find a periodic vowel region, favouring the middle/later stressed vowel.
            candidates = []
            for start in range(2*PERIOD, len(samples)-9*PERIOD, 8):
                a = samples[start:start+4*PERIOD]
                b = samples[start+PERIOD:start+5*PERIOD]
                energy = np.linalg.norm(a)
                match = np.dot(a, b) / max(1, energy*np.linalg.norm(b))
                candidates.append((max(0, match)**5 * energy * (0.8+0.4*start/len(samples)), start))
            _, loop = max(candidates)
            release = loop + 4 * PERIOD
            blend = np.linspace(0, 1, PERIOD)
            samples[release-PERIOD:release] = (
                (1-blend)*samples[release-PERIOD:release] + blend*samples[loop-PERIOD:loop])
            edge = np.linspace(0, 1, 33)
            samples[:33] *= edge
            samples[-33:] *= edge[::-1]
            pcm = np.rint(101*samples / max(abs(samples))).astype(np.int8)
            yield word, pcm, loop, release

def write_table(path):
    rows = ["/* Generated by build_sung_words.py. See docs/VOCAL_CREDITS.md. */"]
    entries = []
    for word, samples, loop, release in render_words():
        rows.append(f"static const int8_t sung_{word}[{len(samples)}]={{")
        rows.extend("  "+",".join(map(str, samples[i:i+32]))+"," for i in range(0, len(samples), 32))
        rows.append("};")
        entries.append(f"  {{sung_{word},sizeof sung_{word},{loop},{release},{loop},{{6,1,5}},{F0:.7f}f}},")
        print(word, len(samples), loop, release)
    Path(path).write_text("\n".join(rows)+"\n#define AQUORA_SUNG_WORDS \\\n"+" \\\n".join(entries)+"\n")

if __name__ == "__main__":
    write_table(sys.argv[1])
