#!/usr/bin/env python3
"""Pack the original signed-eight-bit sample tables without changing a sample."""
import argparse
from pathlib import Path
import re


TABLES = ("drum_waves", "vocal_samples", "vocal_day", "vocal_you",
          "vocal_extensions", "vocal_dreams")
ARRAY = re.compile(r"static const int8_t (\w+_flash)\[[^=]+\s*=\s*\{([^;]+);")


def encode(pcm, order):
    nibbles = []
    previous = older = 0
    for sample in pcm:
        predicted = previous if order == 1 else 2 * previous - older
        residual = (sample - predicted + 128) % 256 - 128
        if -7 <= residual <= 7:
            nibbles.append(residual + 7)
        else:
            nibbles.extend((15, sample & 15, sample >> 4))
        older, previous = previous, sample
    nibbles.append(0)
    return bytes(lo | hi << 4 for lo, hi in zip(nibbles[::2], nibbles[1::2]))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dsp", type=Path, help="Path to the DSP sample tables")
    args = parser.parse_args()
    declarations = ["/* Generated by device/tools/pack_sample_pcm.py. */"]
    unpack = ["#define SR_LOAD_SAMPLE_PCM() do { \\"]
    raw_total = packed_total = 0
    for table in TABLES:
        for name, body in ARRAY.findall((args.dsp / (table + ".inc")).read_text()):
            pcm = bytes(int(x) & 255 for x in re.findall(r"-?\d+", body))
            candidates = [encode(pcm, order) for order in (1, 2)]
            order = min(range(1, 3), key=lambda i: len(candidates[i - 1]))
            data = candidates[order - 1]
            raw_total += len(pcm)
            dest = name.replace("_flash", "_pcm")
            if len(data) >= len(pcm):
                packed_total += len(pcm)
                declarations.append(f"static const int8_t {name}[{len(pcm)}]={{")
                values = [str(x if x < 128 else x - 256) for x in pcm]
                unpack.append(f"  memcpy({dest},{name},sizeof {dest}); \\")
            else:
                packed_total += len(data)
                name += "_packed"
                declarations.append(f"static const uint8_t {name}[{len(data)}]={{")
                values = [str(x) for x in data]
                unpack.append(f"  unpack_sample_pcm({dest},sizeof {dest},{name},{order}); \\")
            for offset in range(0, len(values), 32):
                declarations.append("  " + ",".join(values[offset:offset + 32]) + ",")
            declarations.append("};")
    unpack.append("} while(0)")
    (args.dsp / "sample_pcm_packed.inc").write_text("\n".join(declarations + unpack) + "\n")
    print(f"Sample flash: {raw_total} -> {packed_total} bytes ({raw_total-packed_total} saved before decoder)")


if __name__ == "__main__":
    main()
