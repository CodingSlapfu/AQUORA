"""Genuine audio-active host frames; encode only dynamic UI pages as APNG."""
from pathlib import Path
from PIL import Image
import os,subprocess,sys,json,wave,array,math,hashlib
host,out=sys.argv[1],Path(sys.argv[2]);out.mkdir(parents=True,exist_ok=True)
def run(name,commands,env=None):
 d=out/name;d.mkdir(exist_ok=True);p=d/'script.txt';p.write_text('\n'.join(commands)+'\n')
 r=subprocess.run([host,str(p),str(d)],capture_output=True,text=True,env=dict(os.environ,AQUORA_TEST_SEED='1',**(env or {})))
 (d/'panel.log').write_text(r.stdout+r.stderr);assert r.returncode==0,r.stdout+r.stderr
 return d
pages={'play':['tap HOME'],'sound':['turn ALGO 1','key 6 down'],'evolve':['turn ALGO 2'],
'mixer':['turn ALGO 3'],'mix-strip':['turn ALGO 3','tap FX'],'drums':['turn ALGO 4'],
'air':['turn ALGO 6','tap EDIT'],'appearance':['turn ALGO 5','turn SELECT 1','spin K1 2','spin K3 1']}
provenance=[]
for name,nav in pages.items():
 commands=['master 2048','tap PLAY','wait 4500']+nav+['wait 120','expect running 1','shot still.png']
 dynamic=name in ('sound','evolve','mixer','mix-strip')
 if dynamic:
  for frame in range(40):commands += ['wait 100',f'shot f{frame:02}.png']
 d=run(name,commands)
 Image.open(d/'still.png').save(out/f'{name}-065.png')
 if dynamic:
  frames=[Image.open(d/f'f{n:02}.png').convert('RGB') for n in range(40)]
  assert all(im.size==(240,240) for im in frames)
  unique=len({im.tobytes() for im in frames});assert unique>5,(name,unique)
  target=out/f'{name}-065.apng'
  frames[0].save(target,format='PNG',save_all=True,append_images=frames[1:],duration=100,loop=0,optimize=True)
  with Image.open(target) as im:assert im.n_frames>=6 and im.size==(240,240)
  assert target.stat().st_size<1600000,(name,target.stat().st_size)
  provenance.append({'page':name,'transport':'PLAY','frames':40,'fps':10,'seconds':4,'unique_frames':unique,'sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'source':'actual host RGB565 LCD renderer + live sr_render'})
# Independent branded startup is static and never submits a visualizer job.
run('intro',['expect intro 1','expect reset_visual_counters 1','wait 500','shot a.png','wait 500','shot b.png','expect geometry_jobs 0','expect worker_jobs 0'],{'AQUORA_TEST_INTRO':'1'})
assert Image.open(out/'intro/a.png').tobytes()!=Image.open(out/'intro/b.png').tobytes()
# New secondary field: animated, foreground on both canvases, hidden on intro.
for background in range(2):
 commands=['master 2048','turn ALGO 5','turn SELECT 1',f'spin K3 {background}','spin K4 1','tap HOME','tap PLAY','wait 1500']
 for n in range(12):commands+=['wait 100',f'shot f{n:02}.png']
 commands+=['expect nodal_profiles 1']
 run(f'resonance-b{background}',commands)
 for worker in ('off','bad','late'):
  run(f'resonance-{background}-{worker}',commands,{'FM1_WORKER_TEST':worker})
# Listen at comparable RMS, all generated by the same current host firmware.
for mode in range(3):
 d=run(f'mode-{mode}',['master 2048','spin K1 1','turn ALGO 2']+['tap EDIT']*4+[f'spin K1 {mode}','tap HOME','tap PLAY','wait 2500','wav mode.wav','wait 16000','wavstop'])
 with wave.open(str(d/'mode.wav'),'rb') as w:params=w.getparams();pcm=array.array('h',w.readframes(w.getnframes()))
 rms=math.sqrt(sum(x*x for x in pcm)/len(pcm));gain=min(4000/max(rms,1),30000/max(max(abs(x) for x in pcm),1))
 norm=array.array('h',(round(x*gain) for x in pcm))
 with wave.open(str(out/f'mode-{mode}-matched.wav'),'wb') as w:w.setparams(params);w.writeframes(norm.tobytes())
(out/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')
print('PASS four real 40-frame/240px APNGs, eight UI stills, static intro, new field worker paths, three level-matched music previews')
