import {readFileSync} from 'node:fs';
import {webcrypto} from 'node:crypto';
import vm from 'node:vm';
const page=readFileSync(process.argv[2],'utf8');
const meta=JSON.parse(page.match(/const meta = (\{.*?\});/)[1]);
const helper=page.match(/async function candidateHashOk\(raw\) \{[\s\S]*?\n\}/)[0];
const context=vm.createContext({crypto:webcrypto,Uint8Array,Array,meta});
vm.runInContext(helper,context);
const raw=new Uint8Array(readFileSync(process.argv[3]));
if(!await context.candidateHashOk(raw))throw Error('Exact candidate hash rejected');
raw[1000]^=1;
if(await context.candidateHashOk(raw))throw Error('Changed candidate hash accepted');
if(!page.includes('if (!await candidateHashOk(pkg))'))throw Error('Gate not used before enabling installer');
console.log('PASS exact FWSC accepted; one-byte changed same-identity FWSC rejected before enabling installer');
